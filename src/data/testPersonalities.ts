export function speakingSpeedLabel(speed: number | null): string {
  if (speed == null) return 'N/A'
  if (speed < 0.9) return 'Slow'
  if (speed > 1.1) return 'Fast'
  return 'Normal'
}

export function nextPersonalityId(personalities: TestPersonality[]): string {
  const max = personalities.reduce((highest, personality) => {
    const value = Number(personality.id)
    return Number.isFinite(value) ? Math.max(highest, value) : highest
  }, 8000)
  return String(max + 1)
}
